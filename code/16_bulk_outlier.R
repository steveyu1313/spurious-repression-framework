suppressPackageStartupMessages(library(data.table))
B <- readRDS("./08_QC_Revision/tables/bulk_recheck.rds")
mat <- B$mat; grp <- B$group
pca <- prcomp(t(mat), scale. = TRUE)
pd <- data.table(sample = rownames(pca$x), PC1 = pca$x[, 1], PC2 = pca$x[, 2], Group = grp)
print(as.data.frame(pd[order(-abs(PC1))][1:6]))
cat("\n样本分位数:\n")
q <- t(apply(mat, 2, quantile, c(0, .25, .5, .75, 1)))
print(round(q[order(-abs(pd$PC1))[1:4], ], 2))
cat("\n各样本中位数范围:", round(range(apply(mat, 2, median)), 2), "\n")
mm <- apply(mat, 2, median)
print(round(sort(mm)[c(1:3, 48:50)], 2))
cat("\n异常样本与整体相关:\n")
cm <- cor(mat)
bad <- names(which.min(apply(cm, 1, median)))
cat("最低中位相关样本:", bad, " 中位 r =", round(min(apply(cm, 1, median)), 3), "\n")
